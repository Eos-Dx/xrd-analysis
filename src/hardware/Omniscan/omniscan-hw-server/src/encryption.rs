/// Data access audit log entry
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DataAccessLog {
    pub timestamp: chrono::DateTime<chrono::Utc>,
    pub user_id: String,
    pub operation: DataOperation,
    pub resource: String,
    pub success: bool,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum DataOperation {
    Read,
    Write,
    Delete,
    Export,
}

/// Secure data storage with encryption and access logging
pub struct SecureStorage {
    encryption_service: EncryptionService,
    access_logs: Vec<DataAccessLog>,
}

impl SecureStorage {
    pub fn new(key_manager: &KeyManager) -> Result<Self> {
        Ok(Self {
            encryption_service: key_manager.get_encryption_service()?,
            access_logs: Vec::new(),
        })
    }
    
    /// Store encrypted data
    pub fn store(&mut self, key: &str, data: &[u8], user_id: String) -> Result<()> {
        let encrypted = self.encryption_service.encrypt(data)?;
        
        // TODO: Store in database with proper indexing
        let path = format!("data/encrypted/{}.json", key);
        if let Some(parent) = Path::new(&path).parent() {
            std::fs::create_dir_all(parent)?;
        }
        
        let json = serde_json::to_string(&encrypted)?;
        std::fs::write(&path, json)?;
        
        // Log access
        self.log_access(user_id, DataOperation::Write, key.to_string(), true);
        
        Ok(())
    }
    
    /// Retrieve and decrypt data
    pub fn retrieve(&mut self, key: &str, user_id: String) -> Result<Vec<u8>> {
        let path = format!("data/encrypted/{}.json", key);
        let json = std::fs::read_to_string(&path)?;
        let encrypted: EncryptedData = serde_json::from_str(&json)?;
        
        let plaintext = self.encryption_service.decrypt(&encrypted)?;
        
        // Log access
        self.log_access(user_id, DataOperation::Read, key.to_string(), true);
        
        Ok(plaintext)
    }
    
    /// Log data access event
    fn log_access(&mut self, user_id: String, operation: DataOperation, resource: String, success: bool) {
        let log = DataAccessLog {
            timestamp: chrono::Utc::now(),
            user_id,
            operation,
            resource,
            success,
        };
        
        // TODO: Persist to audit database
        tracing::info!("Data access logged: {:?}", log);
        self.access_logs.push(log);
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    
    #[test]
    fn test_encryption_decryption() {
        let key = EncryptionService::generate_key();
        let service = EncryptionService::new(&key).unwrap();
        
        let plaintext = b"Patient data: XRD analysis results";
        let encrypted = service.encrypt(plaintext).unwrap();
        let decrypted = service.decrypt(&encrypted).unwrap();
        
        assert_eq!(plaintext.as_slice(), decrypted.as_slice());
    }
    
    #[test]
    fn test_encrypted_data_serialization() {
        let key = EncryptionService::generate_key();
        let service = EncryptionService::new(&key).unwrap();
        
        let plaintext = b"Sensitive medical data";
        let encrypted = service.encrypt(plaintext).unwrap();
        
        // Serialize to JSON
        let json = serde_json::to_string(&encrypted).unwrap();
        
        // Deserialize
        let deserialized: EncryptedData = serde_json::from_str(&json).unwrap();
        
        // Decrypt
        let decrypted = service.decrypt(&deserialized).unwrap();
        assert_eq!(plaintext.as_slice(), decrypted.as_slice());
    }
    
    #[test]
    fn test_wrong_key_fails() {
        let key1 = EncryptionService::generate_key();
        let key2 = EncryptionService::generate_key();
        
        let service1 = EncryptionService::new(&key1).unwrap();
        let service2 = EncryptionService::new(&key2).unwrap();
        
        let plaintext = b"Secret data";
        let encrypted = service1.encrypt(plaintext).unwrap();
        
        // Decryption with wrong key should fail
        assert!(service2.decrypt(&encrypted).is_err());
    }
}
