/// Encrypted data container
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct EncryptedData {
    /// Base64-encoded ciphertext
    pub ciphertext: String,
    /// Base64-encoded nonce (96-bit)
    pub nonce: String,
    /// Version of encryption scheme
    pub version: u32,
}

/// Data encryption service
pub struct EncryptionService {
    cipher: Aes256Gcm,
}

impl EncryptionService {
    /// Create new encryption service with provided key
    /// 
    /// TODO: Integrate with TPM for hardware-backed key storage
    /// For production, keys should be:
    /// 1. Generated by TPM
    /// 2. Never exposed in plaintext
    /// 3. Bound to specific hardware
    /// 4. Backed up securely with key escrow
    pub fn new(key: &[u8; 32]) -> Result<Self> {
        let cipher = Aes256Gcm::new(key.into());
        Ok(Self { cipher })
    }
    
    /// Generate a new random encryption key
    /// 
    /// WARNING: For production, use TPM-generated keys
    pub fn generate_key() -> [u8; 32] {
        let mut key = [0u8; 32];
        OsRng.fill_bytes(&mut key);
        key
    }
    
    /// Encrypt data with AES-256-GCM
    pub fn encrypt(&self, plaintext: &[u8]) -> Result<EncryptedData> {
        // Generate random nonce (96-bit for GCM)
        let mut nonce_bytes = [0u8; 12];
        OsRng.fill_bytes(&mut nonce_bytes);
        let nonce = GenericArray::from(nonce_bytes);
        
        // Encrypt
        let ciphertext = self.cipher
            .encrypt(&nonce, plaintext)
            .map_err(|e| anyhow!("Encryption failed: {}", e))?;
        
        Ok(EncryptedData {
            ciphertext: general_purpose::STANDARD.encode(&ciphertext),
            nonce: general_purpose::STANDARD.encode(&nonce_bytes),
            version: 1,
        })
    }
    
    /// Decrypt data
    pub fn decrypt(&self, encrypted: &EncryptedData) -> Result<Vec<u8>> {
        if encrypted.version != 1 {
            return Err(anyhow!("Unsupported encryption version: {}", encrypted.version));
        }
        
        // Decode base64
        let ciphertext = general_purpose::STANDARD
            .decode(&encrypted.ciphertext)
            .map_err(|e| anyhow!("Invalid ciphertext encoding: {}", e))?;
        
        let nonce_bytes = general_purpose::STANDARD
            .decode(&encrypted.nonce)
            .map_err(|e| anyhow!("Invalid nonce encoding: {}", e))?;
        
        if nonce_bytes.len() != 12 {
            return Err(anyhow!("Invalid nonce length: {}", nonce_bytes.len()));
        }
        
        let nonce_array: [u8; 12] = nonce_bytes.try_into()
            .map_err(|_| anyhow!("Failed to convert nonce to array"))?;
        let nonce = GenericArray::from(nonce_array);
        
        // Decrypt
        let plaintext = self.cipher
            .decrypt(&nonce, ciphertext.as_ref())
            .map_err(|e| anyhow!("Decryption failed: {}", e))?;
        
        Ok(plaintext)
    }
    
    /// Encrypt and save data to file
    pub fn encrypt_to_file<P: AsRef<Path>>(&self, plaintext: &[u8], path: P) -> Result<()> {
        let encrypted = self.encrypt(plaintext)?;
        let json = serde_json::to_string_pretty(&encrypted)?;
        std::fs::write(path, json)?;
        Ok(())
    }
    
    /// Load and decrypt data from file
    pub fn decrypt_from_file<P: AsRef<Path>>(&self, path: P) -> Result<Vec<u8>> {
        let json = std::fs::read_to_string(path)?;
        let encrypted: EncryptedData = serde_json::from_str(&json)?;
        self.decrypt(&encrypted)
    }
}

